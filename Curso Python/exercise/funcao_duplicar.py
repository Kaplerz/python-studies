def duplicar(numero):
    return numero * 2
def triplicar(numero):
    return numero * 3
def quadruplicar(numero):
    return numero * 4

resultado = duplicar(10)
resultado2 = triplicar(10)
resultado3 = quadruplicar(10)

print(f'O resultado da duplicação é: {resultado}, da triplicação é: {resultado2} e da quadruplicação é: {resultado3}')
    
